def build_zip(files: dict[str, bytes]) -> bytes:
    import io

    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for name in sorted(files):
            info = zipfile.ZipInfo(name, date_time=FIXED_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            archive.writestr(info, files[name])
    return buffer.getvalue()


def build(name: str, spec: dict[str, str]) -> dict[str, bytes]:
    manifest = dict(MANIFEST)
    manifest["name"] = spec["name"]
    files = {
        "manifest.json": (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode(),
        "schema/schema.xsd": spec["xsd"].encode(),
        "data/sample.xml": spec["sample"].encode(),
    }
    package = build_zip(files)
    directory = EXAMPLES / name
    directory.mkdir(parents=True, exist_ok=True)
    diagnostics: dict[str, bytes] = {
        f"{name}/{spec['package']}": package,
        f"{name}/prompt.txt": (spec["prompt"] + "\n").encode(),
        f"{name}/source/manifest.json": files["manifest.json"],
        f"{name}/source/schema.xsd": files["schema/schema.xsd"],
        f"{name}/source/sample.xml": files["data/sample.xml"],
        f"{name}/README.md": (
            f"# {name.replace('-', ' ').title()} example\n\n"
            "Synthetic DDSP package used by the demo, benchmarks and golden tests.\n"
            "It contains no third-party or customer data.\n\n"
            f"* package: `{spec['package']}`\n"
            "* source: `source/` (XSD + sample data, zipped into the package)\n"
            "* prompt: `prompt.txt`\n\n"
            "Regenerate with `python scripts/build_examples.py`.\n"
        ).encode(),
    }
    return diagnostics


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify committed files match generated output instead of writing",
    )
    args = parser.parse_args(argv)

    failures = 0
    for name, spec in EXAMPLE_SPECS.items():
        outputs = build(name, spec)
        for relative, payload in outputs.items():
            path = EXAMPLES / relative
            if args.check:
                if not path.exists() or path.read_bytes() != payload:
                    print(f"out of date: {path.relative_to(ROOT)}")
                    failures += 1
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(payload)
                print(f"wrote {path.relative_to(ROOT)}")
    if args.check and failures:
        print(f"{failures} file(s) out of date", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
