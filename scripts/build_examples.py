# Deterministic PNG logo so that image bindings can be compiled and previewed
# --------------------------------------------------------------------------- #
def _png(width: int, height: int, pixel: callable[[int, int], tuple[int, int, int]]) -> bytes:
    rows = bytearray()
    for y in range(height):
        rows.append(0)  # filter type 0
        for x in range(width):
            rows.extend(pixel(x, y))

    def chunk(tag: bytes, payload: bytes) -> bytes:
        return (
            struct.pack(">I", len(payload))
            + tag
            + payload
            + struct.pack(">I", zlib.crc32(tag + payload) & 0xFFFFFFFF)
        )

    header = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", header)
        + chunk(b"IDAT", zlib.compress(bytes(rows), 9))
        + chunk(b"IEND", b"")
    )


def _logo_png() -> bytes:
    width, height = 240, 64

    def pixel(x: int, y: int) -> tuple[int, int, int]:
        if x < 8 or x >= width - 8 or y < 8 or y >= height - 8:
            return (255, 255, 255)
        # Simple two-tone mark: dark blue field with a light diagonal band.
        if abs((x - 40) - (y * 3)) < 14:
            return (96, 165, 250)
        return (15, 42, 84)

    return _png(width, height, pixel)


LOGO_B64 = base64.b64encode(_logo_png()).decode("ascii")


