def test_lost_resolved_binding_fails_the_gate(tmp_path: Path) -> None:
    corpus = _corpus(tmp_path, count=2)
    baseline = _baseline_file(tmp_path, documents=2, bindings=6, resolved=6)
    # Force the runner to see a smaller resolved count by changing the baseline
    # (the synthetic documents resolve all three bindings each).
    baseline = _baseline_file(tmp_path, documents=2, bindings=6, resolved=7)
    summary = run(
        corpus=corpus,
        output=tmp_path / "out",
        baseline_path=baseline,
        expected=2,
    )
    assert summary["verdict"] == "failed"
    assert summary["classification"]["lost_resolved"] == 1


def test_unstable_digest_fails_the_gate(tmp_path: Path, monkeypatch) -> None:
    corpus = _corpus(tmp_path, count=1)
    baseline = _baseline_file(tmp_path, documents=1, bindings=3, resolved=3)
    calls = {"count": 0}

    def fake_analyze_once(document, *, limits):
        calls["count"] += 1
        return {
            "label": document.label,
            "sha256": document.sha256,
            "schema_source": "projectdata",
            "report_version": "1.0",
            "bindings": 3,
            "statuses": {"resolved": 3, **{key: 0 for key in STATUS_KEYS if key != "resolved"}},
            "resolved_with_evidence": 3,
            "resolved_without_evidence": 0,
            "graph_digest": "a" * 64 if calls["count"] % 2 else "b" * 64,
            "graph_nodes": 2,
            "graph_edges": 1,
            "resolves_to_with_evidence": 1,
            "evidence_coverage_ratio": 1.0,
            "unresolved_by_status": {},
            "duplicate_links": 0,
            "scope_mismatches": 0,
            "diagnostics": [],
            "graph_json": "{}",
        }

    monkeypatch.setattr("scripts.d365_regression._analyze_once", fake_analyze_once)
    summary = run(
        corpus=corpus,
        output=tmp_path / "out",
        baseline_path=baseline,
        expected=1,
    )
    assert summary["digest_stability"]["stable"] is False
    assert summary["verdict"] == "failed"


