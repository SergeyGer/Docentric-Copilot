ROOT = Path(__file__).resolve().parent.parent.parent

ELEMENTS = (
    ElementSpec(1, "Field", "MainData", "@Number", "System.String"),
    ElementSpec(2, "List", "MainData", "Lines/Line", None, child_ids=(3,)),
    ElementSpec(3, "Field", ".", "@ItemId", "System.String"),
)
CONTROLS = (
    ControlSpec(alias="Field", tag="Field", sdt_id=1),
    ControlSpec(alias="List", tag="List", sdt_id=2),
    ControlSpec(alias="Field", tag="Field", sdt_id=3),
)


def _docx(item_index: int = 1) -> bytes:
    project_data = build_embedded_project_data(ELEMENTS)
    return build_docx(
        document_controls=CONTROLS,
        custom_parts=project_data_parts(project_data, item_index=item_index),
    )


def _baseline_file(tmp_path: Path, *, documents: int, bindings: int, resolved: int) -> Path:
    statuses = dict.fromkeys(STATUS_KEYS, 0)
    statuses["resolved"] = resolved
    path = tmp_path / "baseline.json"
    path.write_text(
        json.dumps(
            {
                "d365": {
                    "documents": documents,
                    "bindings": bindings,
                    "resolved_with_evidence": resolved,
                    "resolved_without_evidence": 0,
                    "unresolved": bindings - resolved,
                    "statuses": statuses,
                }
            }
        ),
        encoding="utf-8",
    )
    return path


def _corpus(tmp_path: Path, count: int = 2) -> Path:
    corpus = tmp_path / "corpus"
    corpus.mkdir()
    for index in range(1, count + 1):
        (corpus / f"document-{index}.docx").write_bytes(_docx(item_index=index))
    return corpus


def test_analyze_document_is_deterministic_and_private() -> None:
    document = CorpusDocument(label="synthetic.docx", payload=_docx())
    record = analyze_document(document, limits=ReferenceLimits())
    assert record["digest_stable"] is True
    assert len(record["graph_digest"]) == 64
    assert record["bindings"] == 3
    assert record["statuses"]["resolved"] == 3
    assert record["sha256"] == document.sha256
    assert isinstance(record["graph_json"], str) and record["graph_json"]


def test_scope_mismatch_ignores_collection_aggregating_elements() -> None:
    def edge() -> SimpleNamespace:
        return SimpleNamespace(
            type=EdgeType.RESOLVES_TO,
            status=SimpleNamespace(value="resolved"),
            source="source",
            target="target",
            resolution_status="resolved",
        )

    def graph(element_kind: ElementKind | None, collection: bool) -> SimpleNamespace:
        return SimpleNamespace(
            nodes=[
                SimpleNamespace(
                    id="source", kind=SimpleNamespace(value="element"), element_kind=element_kind
                ),
                SimpleNamespace(
                    id="target", kind=SimpleNamespace(value="schema_field"), collection=collection
                ),
            ],
            edges=[edge()],
        )

    assert _scope_mismatches(graph(ElementKind.FIELD, False)) == 0
    assert _scope_mismatches(graph(ElementKind.FIELD, True)) == 1
    assert _scope_mismatches(graph(ElementKind.LIST, True)) == 0
    assert _scope_mismatches(graph(ElementKind.LIST, False)) == 1
    assert _scope_mismatches(graph(ElementKind.GROUP, True)) == 0
    assert _scope_mismatches(graph(ElementKind.SUMMARY_FIELD, True)) == 0


def test_run_publishes_only_aggregate_facts(tmp_path: Path) -> None:
    corpus = _corpus(tmp_path)
    baseline = _baseline_file(tmp_path, documents=2, bindings=6, resolved=6)
    output = tmp_path / "out"
    summary = run(
        corpus=corpus,
        output=output,
        baseline_path=baseline,
        expected=2,
    )
    assert summary["verdict"] == "passed"
    assert summary["documents_discovered"] == 2
    assert summary["documents_processed"] == 2
    assert summary["current"]["bindings"] == 6
    assert summary["current"]["statuses"]["resolved"] == 6
    assert summary["digest_stability"]["stable"] is True
    assert summary["classification"]["lost_resolved"] == 0
    assert summary["classification"]["new_unresolved"] == 0

    public = (output / "summary.json").read_text(encoding="utf-8")
    assert "document-1.docx" not in public
    assert "synthetic" not in public
    assert "sha256" not in public
    assert ".docx" not in public
    assert "reference-corpus" not in public
    assert "private" in public

    private = output / "private"
    assert (private / "documents.jsonl").exists()
    assert (private / "manifest.json").exists()
    assert (private / "baseline_digests.json").exists()
    assert len(list((private / "graphs").glob("*.json"))) == 2
    first = json.loads((private / "documents.jsonl").read_text(encoding="utf-8").splitlines()[0])
    assert first["label"].endswith(".docx")
    assert len(first["sha256"]) == 64


