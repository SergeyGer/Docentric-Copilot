def test_baseline_requires_d365_aggregate(tmp_path: Path) -> None:
    path = tmp_path / "baseline.json"
    path.write_text(json.dumps({"schema": "other"}), encoding="utf-8")
    try:
        _baseline(path)
    except SystemExit as exc:
        assert "d365" in str(exc)
    else:  # pragma: no cover - defensive
        raise AssertionError("baseline without d365 must be rejected")


