"""Synthetic D365 embedded-schema evidence in the unified ReferenceGraph (#26).

Every fixture is generated by test code: no Docentric corpus file, fragment or
value is used.
"""

from __future__ import annotations

from pathlib import Path

from docentric_copilot.reference import (
    BindingStatus,
    EdgeType,
    GraphStatus,
    NodeKind,
    SchemaSource,
    analyze_d365_bytes,
    build_reference_graph,
    graph_json,
    inspect_reference_bundle,
)

from tests.reference_fixtures import (
    ControlSpec,
    ElementSpec,
    build_docx,
    build_embedded_project_data,
    build_project_data,
    project_data_parts,
)

SCHEMA_FREE_ELEMENTS = (ElementSpec(900, "Field", "MainData", "@Number"),)


def _embedded_docx() -> bytes:
    elements = (
        ElementSpec(1, "Field", "MainData", "@Number", "System.String"),
        ElementSpec(2, "Field", "MainData", "@Missing", "System.String"),
        ElementSpec(3, "Field", "MainData", "@Number", "System.Decimal"),
        ElementSpec(4, "Field", "MainData", "@Total + 1", "System.String"),
        ElementSpec(5, "List", "MainData", "Lines/Line", None, child_ids=(6,)),
        ElementSpec(6, "Field", ".", "@ItemId", "System.String"),
    )
    controls = tuple(
        ControlSpec(alias=item.element_type, tag=item.element_type, sdt_id=item.element_id)
        for item in elements
    )
    project_data = build_embedded_project_data(elements)
    custom = project_data_parts(project_data, item_index=1)
    return build_docx(document_controls=controls, custom_parts=custom)


def _schema_free_docx() -> bytes:
    custom = project_data_parts(build_project_data(SCHEMA_FREE_ELEMENTS))
    controls = (ControlSpec(alias="Field", tag="Field", sdt_id=900),)
    return build_docx(document_controls=controls, custom_parts=custom)


def _bundle(tmp_path: Path):
    (tmp_path / "Embedded.docx").write_bytes(_embedded_docx())
    (tmp_path / "NoSchema.docx").write_bytes(_schema_free_docx())
    return inspect_reference_bundle(tmp_path)


def _reports(bundle) -> dict[str, object]:
    by_name = {
        "Embedded.docx": _embedded_docx(),
        "NoSchema.docx": _schema_free_docx(),
    }
    reports: dict[str, object] = {}
    for document in bundle.report.documents:
        reports[document.sha256] = analyze_d365_bytes(
            by_name[document.filename], filename=document.filename
        )
    return reports


def _edges_by_element(graph, element_id: str, part_suffix: str = "") -> list:
    nodes = {node.id: node for node in graph.nodes}
    result = []
    for edge in graph.edges:
        if edge.type is not EdgeType.RESOLVES_TO:
            continue
        source = nodes[edge.source]
        if source.element_id != element_id:
            continue
        if part_suffix and not (source.part or "").endswith(part_suffix):
            continue
        result.append(edge)
    return result


def test_d365_schema_nodes_and_edges_carry_provenance(tmp_path: Path) -> None:
    bundle = _bundle(tmp_path)
    graph = build_reference_graph(
        bundle.report, bundle.schemas, d365=_reports(bundle), documents=bundle.payloads
    )

    assert graph.schema_source is SchemaSource.PROJECT_DATA
    assert graph.schema_provider_types == ["d365_project_data"]
    assert graph.runtime_compatibility == "not_tested"
    assert graph.compilable is False

    number_edges = _edges_by_element(graph, "1")
    assert number_edges
    resolved = [edge for edge in number_edges if edge.status is GraphStatus.RESOLVED]
    assert len(resolved) == 1
    edge = resolved[0]
    assert edge.resolution_status == BindingStatus.RESOLVED.value
    assert edge.evidence["schema_source"] == "d365_project_data"
    assert edge.evidence["source_id"]
    assert edge.evidence["evidence"].startswith("customXml/item")
    assert edge.evidence["canonical_path"] == "MainData/Root/@Number"

    nodes = {node.id: node for node in graph.nodes}
    schema_node = nodes[edge.target]
    assert schema_node.kind is NodeKind.SCHEMA_FIELD
    assert schema_node.schema_source == "d365_project_data"
    assert schema_node.source_id
    assert schema_node.evidence_location
    assert "customXml/item" in schema_node.evidence_location
    assert schema_node.schema_path == "MainData/Root/@Number"
    assert schema_node.data_type == "xs:string"

    list_edges = _edges_by_element(graph, "5")
    assert list_edges and list_edges[0].status is GraphStatus.RESOLVED
    target = nodes[list_edges[0].target]
    assert target.collection is True
    assert target.schema_path == "MainData/Root/Lines/Line"


def test_non_resolved_statuses_never_become_resolved_edges(tmp_path: Path) -> None:
    bundle = _bundle(tmp_path)
    graph = build_reference_graph(bundle.report, bundle.schemas, d365=_reports(bundle))
    by_element = {
        element_id: _edges_by_element(graph, element_id)[0] for element_id in ("2", "3", "4", "900")
    }
    expected = {
        "2": BindingStatus.UNKNOWN_PATH.value,
        "3": BindingStatus.TYPE_MISMATCH.value,
        "4": BindingStatus.UNSUPPORTED_EXPRESSION.value,
        "900": BindingStatus.SCHEMA_UNAVAILABLE.value,
    }
    for element_id, status in expected.items():
        edge = by_element[element_id]
        assert edge.resolution_status == status
        assert edge.status is not GraphStatus.RESOLVED
        nodes = {node.id: node for node in graph.nodes}
        assert nodes[edge.source].status is not GraphStatus.RESOLVED
    # schema_unavailable is not silently reclassified as unknown_path.
    assert by_element["900"].resolution_status != BindingStatus.UNKNOWN_PATH.value
    unresolved = {item.node_id for item in graph.unresolved}
    assert any(item.startswith("element:") for item in unresolved)


def test_summary_reports_evidence_coverage_and_unresolved_by_status(
    tmp_path: Path,
) -> None:
    bundle = _bundle(tmp_path)
    graph = build_reference_graph(bundle.report, bundle.schemas, d365=_reports(bundle))
    summary = graph.summary
    assert summary.resolves_to_edges == 7
    assert summary.resolves_to_resolved == 3
    assert summary.resolves_to_with_evidence == 3
    assert 0.0 < summary.evidence_coverage_ratio < 1.0
    assert summary.unresolved_by_status == {
        "schema_unavailable": 1,
        "type_mismatch": 1,
        "unknown_path": 1,
        "unsupported_expression": 1,
    }
    assert sum(summary.unresolved_by_status.values()) == summary.resolves_to_edges - 3
    assert summary.unresolved_reasons
    assert any(key.startswith("unknown_path") for key in summary.unresolved_reasons)


def test_graph_automatically_uses_embedded_d365_schema(tmp_path: Path) -> None:
    bundle = _bundle(tmp_path)
    automatic = build_reference_graph(bundle.report, bundle.schemas, documents=bundle.payloads)
    explicit = build_reference_graph(bundle.report, bundle.schemas, d365=_reports(bundle))
    assert automatic.schema_provider_types == ["d365_project_data"]
    assert automatic.summary.evidence_coverage_ratio == explicit.summary.evidence_coverage_ratio
    assert graph_json(automatic) == graph_json(explicit)


def test_d365_graph_is_deterministic(tmp_path: Path) -> None:
    bundle = _bundle(tmp_path)
    reports = _reports(bundle)
    first = build_reference_graph(bundle.report, bundle.schemas, d365=reports)
    second = build_reference_graph(bundle.report, bundle.schemas, d365=reports)
    assert graph_json(first) == graph_json(second)
    assert first.graph_digest == second.graph_digest


def test_controls_still_bind_to_elements(tmp_path: Path) -> None:
    bundle = _bundle(tmp_path)
    graph = build_reference_graph(bundle.report, bundle.schemas, d365=_reports(bundle))
    bound = [edge for edge in graph.edges if edge.type is EdgeType.BOUND_TO]
    assert bound
    assert any(edge.source.startswith("control:") for edge in bound)
    controls = [node for node in graph.nodes if node.kind is NodeKind.CONTROL]
    assert controls
